-- E2E 씨앗 데이터 - Rails(`template-ruby-rails`) 스키마 버전.
--
-- `examples.sql`(정본·NestJS 공용)과 **내용은 같고 테이블 이름만 다르다** -
-- Rails 는 `db/schema.rb` 가 분류·라벨·조인 테이블에 다른 이름을 쓴다. 어느
-- 백엔드가 어느 파일을 쓰는지, 그리고 왜 두 벌인지는 README.md 가 정본이다.
-- 격리 계약·정렬 키 설계 같은 공유 근거는 `examples.sql` 머리말이 정본이고
-- 여기서 되풀이하지 않는다 - 같은 설명이 두 파일에 있으면 하나만 고쳐지는
-- 자리가 된다.
--
-- ## 테이블 이름 대응
--
--   | 정본(FastAPI)·NestJS  | Rails(`db/schema.rb`)                            |
--   | ---------------------- | ------------------------------------------------- |
--   | `categories`           | `example_categories`                               |
--   | `tags`                 | `example_tags`                                     |
--   | `example_tags`(조인)   | `example_taggings`(복합 PK: example_id, tag_id)   |
--   | `examples`             | `examples`(컬럼 일치)                              |
--
-- **같은 id·같은 값·같은 시각**을 쓴다 - 그래야 같은 시나리오가 세 백엔드에서
-- 같은 결과를 낸다.
--
-- `docker-compose.e2e.yml` 의 `seed-rails` 서비스가 `-v ON_ERROR_STOP=1` 로
-- 이 파일을 돌린다 - Rails 스키마가 바뀌어 컬럼·테이블이 어긋나면 이 파일이
-- 즉시, 시끄럽게 죽어야 한다(게이트가 초록인 채로 틀리는 모양을 막는다).
--
-- ## `db/seeds.rb` 를 청소하지 않는다 - 이 저장소의 범위에서는 무해하다
--
-- `migrate-rails`(`bin/rails db:prepare`)는 데이터베이스를 새로 만든 경우
-- `db/seeds.rb` 도 함께 돌려 `ExampleCategory`·`ExampleTag` 에 "General"·
-- "Ruby"·"API" 세 행을 얹는다. 형제 저장소(template-typescript-nextjs)는
-- 그 세 행을 지운다 - 참조 목록의 100건 천장을 실제로 넘기는 시나리오가
-- 있어 정렬 순위가 셋만큼 밀리면 그 단정이 깨지기 때문이다. **이 저장소는
-- 그 시나리오가 없다**(examples.spec.ts 는 목록·정렬·페이지 이동을
-- `?title=probe-seed` 로 좁혀서만 보고, 생성 폼 시나리오는 분류·라벨을
-- 이름으로 골라 정확히 짚는다) - 그래서 그 세 행이 남아 있어도 아래 어떤
-- 단언도 흔들리지 않는다. 청소 없이 두는 편이 하우스키핑 SQL 한 벌을 줄인다.
