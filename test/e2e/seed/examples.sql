-- E2E 씨앗 데이터 - 목록·정렬·페이지 이동·상세·생성 폼(분류·라벨 선택지)이
-- 볼 행들. FastAPI(정본)·NestJS 공용 - 두 백엔드는 테이블 이름이 같다
-- (README.md 참고, Rails 는 examples.rails.sql 을 따로 쓴다).
--
-- `docker-compose.e2e.yml` 의 `seed-fastapi`/`seed-nestjs` 서비스가 마이그레이션
-- 직후 돌린다. 게이트는 매 실행 `down -v` 로 볼륨을 지우므로(그 파일 머리말의
-- "Postgres 에 볼륨을 붙이지 않는다" 절) 이 파일이 그 실행의 데이터 전부다.
--
-- ## `ON CONFLICT DO NOTHING` 이 지키는 것 - "한 번만 돈다"가 아니다
--
-- 아래 INSERT 의 `ON CONFLICT` 절을 "어차피 빈 DB 니까 장식"으로 읽고 지우지
-- 마라. `docker compose up --wait` 은 이미 끝난 `seed-*` 컨테이너를 재실행 시
-- 다시 돌릴 수 있다 - 그 절이 없으면 두 번째 실행이 기본 키 충돌로 죽고,
-- 죽는 자리가 `seed-*` 라 스택이 아예 뜨지 않는다.
--
-- ## 왜 HTTP 가 아니라 SQL 인가
--
-- 분류(`categories`)와 라벨(`tags`)에는 쓰기 라우트가 아예 없다
-- (`lib/resources/category.ts`·`tag.ts` 의 `writable: false`) - HTTP 로는
-- 만들 수 없다. 그런데 목록 표의 열 여덟 중 둘이 그 관계이고, 생성 폼의
-- 선택지도 그것이다 - 관계 없이 시드하면 E2E 가 화면의 절반을 못 본다.
--
-- ## 격리 - 왜 이 데이터가 고정이어도 되는가
--
-- 목록 시나리오(auth.spec.ts 의 생성 시나리오는 제외)는 이 행들을 바꾸지
-- 않는다. 목록 단언은 아래 `probe-seed` 접두사로 좁혀서 본다
-- (`?title=probe-seed`, `lib/grid/query.ts` 의 `uiOperator: 'contains'` 를
-- 그대로 태운다) - 다른 시나리오가 만든 행은 그 필터에 걸리지 않는다.
--
-- **생성 시나리오(examples.spec.ts 의 "생성 폼")에게 남는 의무는 하나다: 이
-- 접두사를 쓰지 마라.** 그것만 지키면 목록 시나리오가 그 행을 보지 않는다.
--
-- ## 값을 고른 규칙
--
-- 프로덕션 상수와 같은 값을 쓰지 않는다. id 는 눈에 띄는 고정 패턴
-- (`1111...`·`2222...`·`3333...`)이고, 제목은 전부 `probe-seed` 로 시작한다.
--
-- **정렬 키 넷이 서로 다른 순서를 낸다:**
--
--   | 정렬                    | 순서                                   |
--   | ----------------------- | --------------------------------------- |
--   | `-createdAt`(기본 정렬) | alpha charlie echo foxtrot bravo delta   |
--   | `title`                 | alpha bravo charlie delta echo foxtrot   |
--   | `-score`                | foxtrot bravo delta echo alpha charlie   |
--   | `-updatedAt`            | delta bravo foxtrot echo charlie alpha   |
--
-- 넷이 같은 순서를 내면 정렬 키를 바꿔치기한 결함이 화면에서 안 보인다.
-- `created_at`·`updated_at` 을 서로 다른 값으로 둔 것도 같은 이유다(상세의
-- "수정"이 "생성"을 베끼는 결함을 구별한다).
--
-- charlie 의 점수가 `0`인 것도 의도다 - falsy 값과 "값 없음"을 구별하지
-- 못하는 결함이 이 행에서 드러난다.
--
-- `status` 정렬은 이 파일이 순서를 보장하지 않는다 - Postgres enum 의 정렬은
-- 알파벳순이 아니라 **선언 순서**(draft·active·archived)라 그 값은 백엔드
-- 저장소의 것이다 - Step 12 가 세 갈래에서 실제로 손으로 확인한다.

